import { build } from 'esbuild';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const vendor = join(root, 'src', 'vendor');
const require = createRequire(import.meta.url);
await mkdir(vendor, { recursive: true });
await build({
  stdin: { contents: 'export { WorkletSynthesizer } from "spessasynth_lib";', resolveDir: root, sourcefile: 'pianocraft-soundfont-vendor.js' },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'chrome120',
  outfile: join(vendor, 'spessasynth.js'),
  minify: true,
  legalComments: 'linked',
  banner: { js: '// SpessaSynth browser adapter bundle. See VENDOR-NOTICES.txt and accompanying licenses.' },
});

const notices = ['PianoCraft: offline SoundFont synthesis dependencies.', 'Generated by scripts/prepare-assets.mjs; source code is available from the repositories below.', 'No third-party SoundFont sample bank is bundled.', ''];
for (const name of ['spessasynth_lib', 'spessasynth_core', 'stb-vorbis']) {
  const packageRoot = dirname(dirname(require.resolve(name)));
  const metadata = JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8'));
  await copyFile(join(packageRoot, 'LICENSE'), join(vendor, `${name}.LICENSE.txt`));
  notices.push(`${name} ${metadata.version} — ${metadata.license}`, metadata.repository?.url || metadata.homepage || '', `License: ${name}.LICENSE.txt`, '');
  if (name === 'spessasynth_lib') await copyFile(join(packageRoot, 'dist', 'spessasynth_processor.min.js'), join(vendor, 'spessasynth_processor.min.js'));
}
// spessasynth_core includes fflate-derived decompression code in its distribution.
const fflateRoot = dirname(require.resolve('fflate/package.json'));
await copyFile(join(fflateRoot, 'LICENSE'), join(vendor, 'fflate.LICENSE.txt'));
notices.push('fflate — MIT', 'https://github.com/101arrowz/fflate', 'License: fflate.LICENSE.txt', '');
await writeFile(join(vendor, 'VENDOR-NOTICES.txt'), notices.join('\n'));
console.log('Prepared offline SoundFont bundle, worklet and dependency licenses in src/vendor.');
